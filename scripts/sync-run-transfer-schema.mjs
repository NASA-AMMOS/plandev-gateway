#!/usr/bin/env node
/**
 * Regenerate `src/schemas/run-transfer-schema.ts` from the schema in plandev-examples.
 *
 * The schema is authored once, next to the format reference and the fixtures, because it is a
 * producer-facing contract and a producer is the party most likely to be outside PlanDev. It has to
 * be a TypeScript module here (that is how this repo already carries the external-event schemas, and
 * `tsc` does not copy .json into dist), so it is GENERATED rather than transcribed -- a hand-copied
 * schema is a schema that drifts.
 *
 *   node scripts/sync-run-transfer-schema.mjs           # regenerate
 *   node scripts/sync-run-transfer-schema.mjs --check   # fail if stale, for CI
 *
 * Point RUN_TRANSFER_SCHEMA_SOURCE at the file if the examples checkout is somewhere else.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source =
  process.env.RUN_TRANSFER_SCHEMA_SOURCE ??
  resolve(here, '../../../plandev-examples/tools/run_transfer/run-transfer.v1.schema.json');
const target = resolve(here, '../src/schemas/run-transfer-schema.ts');

/**
 * Object keys sorted, arrays left alone.
 *
 * Two reasons. This repo's eslint enforces `sort-keys`, and a generated file is not worth an
 * exemption. And it makes the output deterministic, so `--check` compares content rather than
 * whatever key order the source file happens to be written in. Key order carries no meaning in JSON
 * Schema, so this is lossless -- unlike sorting an ARRAY, which would reorder a variant list.
 */
function sortKeys(value) {
  if (Array.isArray(value)) {
    return value.map(sortKeys);
  }
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map(key => [key, sortKeys(value[key])]),
    );
  }
  return value;
}

const schema = sortKeys(JSON.parse(readFileSync(source, 'utf8')));
if (schema.$schema !== 'http://json-schema.org/draft-07/schema#') {
  console.error(`refusing to sync: ${source} is not draft-07, and this repo pins ajv ^6`);
  process.exit(1);
}

const generated = `// GENERATED by scripts/sync-run-transfer-schema.mjs -- do not edit.
//
// Source of truth: plandev-examples/tools/run_transfer/run-transfer.v1.schema.json,
// which is where the format reference and the fixtures live too. Re-run the script after editing it
// there; \`--check\` fails if this file is stale.
//
// Draft-07, matching the ajv ^6 this repo pins. Authoring 2020-12 and discovering the mismatch at
// runtime is the failure that pin exists to prevent.
export const runTransferSchema = ${JSON.stringify(schema, null, 2)} as const;
`;

if (process.argv.includes('--check')) {
  const current = (() => {
    try {
      return readFileSync(target, 'utf8');
    } catch {
      return '';
    }
  })();
  if (current !== generated) {
    console.error(`stale: ${target} does not match ${source}. Run: node scripts/sync-run-transfer-schema.mjs`);
    process.exit(1);
  }
  console.log('run-transfer schema is up to date');
} else {
  writeFileSync(target, generated);
  console.log(`wrote ${target} from ${source}`);
}
